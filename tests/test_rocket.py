def test_spawn_rocket_horizontal(start_board, expected_board, move):
    b = Board(board_state=start_board)
    
    print(move)
    r1, c1, r2, c2 = move
    b.swap(r1, c1, r2, c2)
    b.last_move = ((r1, c1), (r2, c2))

    assert b.pop() == 4
    assert b.board == expected_board


